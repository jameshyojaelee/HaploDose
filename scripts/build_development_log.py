"""Build traceable Markdown indexes from existing development evidence only.

Reads documentation, root-level dev metadata and optional read-only Slurm
accounting. Does not traverse datasets/environments or execute scientific work.
"""
import argparse
from collections import Counter
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import subprocess


GENERATED = '<!-- Generated by scripts/build_development_log.py; edit source records, then rebuild. -->'
OUTPUTS = ('DEVELOPMENT_INDEX.md','DEVELOPMENT_ATTEMPTS.md','DEVELOPMENT_RUNS.md')
EXCLUDE = {*OUTPUTS,'DEVELOPMENT_LOG.md'}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def slug(text):
    return re.sub(r'[^\w\s-]','',text.lower()).replace(' ','-')


def link(path,label=None):
    value=Path(path).as_posix()
    target=value[5:] if value.startswith('docs/') else '../'+value
    return f'[{label or value}](<{target}>)'


def first_paragraph(text):
    blocks=re.split(r'\n\s*\n',text.strip())
    return next((p for p in blocks if p and not p.startswith(('#','<!--'))),'No opening narrative paragraph recorded.')


def job_ids(value,key=''):
    out=set()
    if isinstance(value,dict):
        for k,v in value.items():out.update(job_ids(v,k))
    elif isinstance(value,list):
        for v in value:out.update(job_ids(v,key))
    elif 'job' in key.lower() and isinstance(value,(str,int)):
        # Exact IDs and common journal strings; exclude source/date seeds.
        for token in re.findall(r'(?<!\d)\d{7,8}(?!\d)',str(value)):
            if 22000000<=int(token)<30000000:out.add(token)
    return out


def write_owned(path,text):
    if path.exists() and GENERATED not in path.read_text():
        raise RuntimeError(f'Refusing to replace an unowned document: {path}')
    path.write_text(text)


def peak_rss(rows):
    values=[]
    for row in rows:
        match=re.fullmatch(r'(\d+(?:\.\d+)?)([KMGTPE]?)',row.get('MaxRSS',''))
        if not match:continue
        multiplier=1024**('KMGTPE'.index(match[2])+1) if match[2] else 1
        values.append((float(match[1])*multiplier,row))
    if not values:return 'not recorded'
    _,row=max(values,key=lambda pair:pair[0])
    return f'{row["MaxRSS"]} ({row["JobID"]}; {len(values)} step records)'


def category(path):
    n=path.stem.upper()
    if any(s in n for s in ('DNTR','SCONE','ANDOR_DNA','ONEK1K','PROSPECTIVE','MEASUREMENT_CHAIN','ALLELE_INTEGRITY','RAW_ROLES')):
        return 'Primary measurements, DNA truth and prospective feasibility'
    if any(s in n for s in ('UNCERTAINTY','MC_PRECISION','CONFIDENCE')):
        return 'Uncertainty, confidence and information limits'
    if any(s in n for s in ('RECOVERY','MEMBERSHIP','CONFIRMATION','JOINT','THINNING','GENE_VETO','GENE_STATE','EXACT_PROFILE_MERGE','PRODUCTION_','SPLIT_DRAW','STATE_INFORMATION','INITIALIZATION','RNA_POPULATION','POOLED_TRADEOFF','REGIONAL_AMPLITUDE','MERGE_POPULATION')):
        return 'Clone recovery, confirmation, merging and false-split/power experiments'
    if any(s in n for s in ('BULK','PROFILE','REFERENCE','AGGREGATION','GENE_FACTORIAL','GENE_PROGRAMME','ATTRIBUTION','OFFSET')):
        return 'Profile and bulk accuracy, aggregation, reference and nuisance models'
    if any(s in n for s in ('HARDENING','BIN_IDENTITY','SPATIAL_IDENTITY','GRAPH_PRECISION','ALLELE_','LOSS_QUANTILE','MIGRATION','SCIENTIFIC_CONTRACT')):
        return 'Computational correctness, identity, contracts and execution'
    return 'Historical reviews, benchmarking rules and manuscript records'


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    p.add_argument('--evidence',type=Path,required=True)
    p.add_argument('--capture-scheduler',action='store_true')
    a=p.parse_args();root=a.root.resolve();evidence=a.evidence.resolve()
    evidence.mkdir(parents=True,exist_ok=True)
    stamp=datetime.now(timezone.utc).isoformat()
    reports=sorted(q for q in (root/'docs').glob('*.md') if q.name not in EXCLUDE)
    ledger_path=root/'benchmarks/hardening/claims.json'
    ledger=json.loads(ledger_path.read_text())
    folders=sorted(q for q in (root/'dev').iterdir() if q.is_dir())
    journals={};ids=job_ids(ledger);discovery={}
    for folder in folders:
        journal=folder/'jobs.json'
        if journal.is_file():
            journals[folder.name]=json.loads(journal.read_text())
            found=job_ids(journals[folder.name]);ids.update(found)
            discovery.setdefault(folder.name,set()).update(found)
        # Bounded one-level metadata inventory. Never recurse into environments.
        for child in folder.iterdir():
            m=re.match(r'(?:analysis|validation)_(\d{7,8})(?:$|\.)',child.name)
            if m:
                ids.add(m[1]);discovery.setdefault(folder.name,set()).add(m[1])
    for report in reports:
        text=report.read_text()
        ids.update(re.findall(r'\bjobs?\s*[:#]?\s*(2[2-9]\d{6})\b',text,re.I))
        # Explicit table rows whose first cell is a recorded Slurm job ID.
        ids.update(re.findall(r'^\|\s*(2[2-9]\d{6})\s*\|',text,re.M))
    scheduler_path=evidence/'scheduler_snapshot.tsv'
    scheduler_error=None
    if a.capture_scheduler:
        cmd=['sacct','--starttime=2026-10-25','--jobs='+','.join(sorted(ids,key=int)),
             '--format=JobID,JobName%80,State%80,Account,QOS,Partition,AllocCPUS,ReqMem,Elapsed,MaxRSS,ExitCode','-P']
        result=subprocess.run(cmd,capture_output=True,text=True)
        if result.returncode==0:scheduler_path.write_text(result.stdout)
        else:scheduler_error=result.stderr.strip()
        (evidence/'scheduler_command.json').write_text(json.dumps(dict(command=cmd,returncode=result.returncode,error=scheduler_error),indent=2)+'\n')
    states={};steps={}
    if scheduler_path.is_file():
        lines=scheduler_path.read_text().splitlines()
        header=lines[0].split('|') if lines else []
        for line in lines[1:]:
            row=dict(zip(header,line.split('|')));jid=row.get('JobID','')
            if jid.isdigit():states[jid]=row
            elif '.' in jid:steps.setdefault(jid.split('.')[0],[]).append(row)
    common=f'{GENERATED}\n\nRecorded at {stamp}. Generated from local evidence; historical results were not rerun.\n'
    register=['# Complete structured attempt register\n',common,
        'This is a lossless Markdown rendering of every top-level field in '+link('benchmarks/hardening/claims.json')+'. '
        'Its source SHA256 is `'+digest(ledger_path)+'`. Older pending/build/status fields are historical checkpoints, '
        'not a statement of current scheduler status. Read [the current overview](DEVELOPMENT_LOG.md) first.\n\n'
        'Full records preserve negative results, assumptions, estimands, methods, thresholds, failures, evidence paths and decisions. '
        'The repeated JSON blocks are intentional: they retain every nested field rather than paraphrasing away unsuccessful attempts.\n']
    register+=['\n## Contents\n\n']
    for key in ledger:register.append(f'- [{key}](#{slug(key)})\n')
    for key,value in ledger.items():
        register.append(f'\n## {key}\n\n')
        if isinstance(value,dict):
            for name in ('report','design','audit','decision','computational_status','identification_status','biological_status'):
                if name not in value:continue
                text=value[name]
                if isinstance(text,str):
                    is_path=name in ('report','design','audit') and len(text)<240 and '\n' not in text
                    rendered=link(text) if is_path and (root/text).is_file() else text
                    register.append(f'- **{name.replace("_"," ")}:** {rendered}\n')
        register.append('\n<!-- ledger-key: '+json.dumps(key)+' -->\n```json\n'+json.dumps(value,indent=2)+'\n```\n')
    register_text=''.join(register)
    recovered={json.loads(k):json.loads(v) for k,v in re.findall(r'<!-- ledger-key: ("[^\n]+") -->\n```json\n(.*?)\n```',register_text,re.S)}
    assert json.dumps(recovered,sort_keys=True)==json.dumps(ledger,sort_keys=True)
    write_owned(root/'docs/DEVELOPMENT_ATTEMPTS.md',register_text)

    index=['# Detailed report and historical chronology index\n',common,
        '[Current overview](DEVELOPMENT_LOG.md) · [Complete ledger](DEVELOPMENT_ATTEMPTS.md) · [Run journal](DEVELOPMENT_RUNS.md)\n\n'
        'Every existing source report is indexed below. Opening passages are quoted from their source and may describe historical states; '
        'they are not new validation or current default claims. Read the linked full report for methods, fixtures, competing explanations and limitations.\n']
    groups={}
    for report in reports:groups.setdefault(category(report),[]).append(report)
    for group,paths in groups.items():
        index.append('\n## '+group+'\n')
        for report in paths:
            text=report.read_text();title=next((s[2:] for s in text.splitlines() if s.startswith('# ')),report.name)
            index.append(f'\n### {title}\n\n'+link(report.relative_to(root),report.name)+'\n\n')
            index.extend('> '+s+'\n' for s in first_paragraph(text).splitlines())
    index.append('\n## Every checkpoint in STATUS.md\n\n'
                 'These links cover every level-two historical checkpoint, including early attempts and reverted changes. '
                 'Undated headings retain their original context; old “current state” sections are superseded by the current overview.\n\n')
    seen=Counter();status_headers=[]
    for lineno,line in enumerate((root/'docs/STATUS.md').read_text().splitlines(),1):
        if not line.startswith('## '):continue
        title=line[3:];base=slug(title);number=seen[base];seen[base]+=1
        anchor=base+('-'+str(number) if number else '')
        status_headers.append(dict(line=lineno,title=title,anchor=anchor))
        index.append(f'- [{title}](STATUS.md#{anchor}) (source line {lineno}).\n')
    write_owned(root/'docs/DEVELOPMENT_INDEX.md',''.join(index))

    runs=['# Development runs, failures and artifact inventory\n',common,
        '[Current overview](DEVELOPMENT_LOG.md) · [Attempt register](DEVELOPMENT_ATTEMPTS.md) · [Report index](DEVELOPMENT_INDEX.md)\n\n'
        'This journal preserves every root-level `dev/*/jobs.json` record verbatim below, plus a bounded inventory of development directories. '
        'A directory is not automatically a scientific experiment, and a submitted command is not automatically a successful result. '
        'Repeated IDs across journals refer to the same scheduler job, not independent replication.\n\n']
    if scheduler_error:runs.append('**[Unverified] Scheduler refresh failed:** '+scheduler_error+'\n\n')
    counts=Counter(r.get('State','').split(' by ')[0].split('+')[0] for r in states.values())
    runs.append('## Scheduler snapshot\n\n'
                f'Job identifiers discovered: **{len(ids)}**; scheduler records available: **{len(states)}**. '
                'Accounting rows describe executable status, not scientific validity. Historical records missing from accounting remain unverified. '
                'IDs are references found in retained metadata, not necessarily jobs first submitted in this session. '
                'Peak RSS below is the largest recorded step RSS, not simultaneous total job memory; '
                'the full per-step accounting is retained in '+link(scheduler_path.relative_to(root),'scheduler snapshot')+'.\n\n')
    runs.append('| State | Jobs |\n|---|---:|\n')
    runs.extend(f'| {k or "unknown"} | {v} |\n' for k,v in sorted(counts.items()))
    runs.append('\n### Per-job states\n\n| Job | State | Account / QOS | Partition | CPUs / requested memory | Elapsed | Exit | Step peak RSS records |\n|---|---|---|---|---|---|---|---|\n')
    for jid in sorted(ids,key=int):
        row=states.get(jid,{})
        rss=peak_rss(steps.get(jid,[]))
        runs.append(f'| {jid} | {row.get("State","[Unverified] no accounting row")} | {row.get("Account","")} / {row.get("QOS","")} | {row.get("Partition","")} | {row.get("AllocCPUS","")} / {row.get("ReqMem","")} | {row.get("Elapsed","")} | {row.get("ExitCode","")} | {rss} |\n')
    runs.append('\n## Development directories and local evidence\n\n'
                'Inventory is limited to the directory itself and known root metadata. Environments, count matrices and raw reads were not traversed. '
                'Entries without a root design/job journal are unclassified workspaces, not inferred successful experiments.\n\n'
                '| Directory | Design | Job journal | Additional root evidence | Known job IDs |\n|---|---|---|---|---|\n')
    for folder in folders:
        relative=folder.relative_to(root)
        design=link(relative/'DESIGN.md','design') if (folder/'DESIGN.md').is_file() else 'not recorded at root'
        journal=link(relative/'jobs.json','jobs') if folder.name in journals else 'not recorded at root'
        evidence_names=[n for n in ('accounting_final.tsv','accounting_checkpoint.tsv','resource_summary_final.json','resource_summary.json','source_integrity.json','source_integrity_checkpoint.json','initial_git_status.txt','README.md') if (folder/n).is_file()]
        local=', '.join(link(relative/n,n) for n in evidence_names) or 'inspect linked directory; no standard root record'
        runs.append(f'| {link(relative,folder.name)} | {design} | {journal} | {local} | '+', '.join(sorted(discovery.get(folder.name,set()),key=int))+' |\n')
    runs.append('\n## Complete recorded job journals\n\n'
                'Commands below are historical records, not instructions executed by this documentation build. '
                'Scheduler snapshots above resolve status where available. Source journals may retain superseded planned roles.\n')
    for name,value in journals.items():
        runs.append('\n### '+name+'\n\n'+link(Path('dev')/name/'jobs.json','source journal')+'\n\n```json\n'+json.dumps(value,indent=2)+'\n```\n')
    write_owned(root/'docs/DEVELOPMENT_RUNS.md',''.join(runs))
    report_manifest={str(q.relative_to(root)):digest(q) for q in reports}
    output_manifest={name:digest(root/'docs'/name) for name in OUTPUTS}
    coverage=dict(generated_at=stamp,ledger_sha256=digest(ledger_path),ledger_fields=len(ledger),
                  ledger_roundtrip_exact=True,source_reports=len(reports),status_checkpoints=len(status_headers),
                  development_directories=len(folders),root_job_journals=len(journals),
                  discovered_job_ids=len(ids),scheduler_rows=len(states),
                  accounting_missing_ids=sorted(ids-set(states),key=int),scheduler_error=scheduler_error,
                  source_report_hashes=report_manifest,output_hashes=output_manifest,
                  scope='Documentation field/link inventory; no scientific result or prior test was revalidated by this build')
    (evidence/'coverage.json').write_text(json.dumps(coverage,indent=2)+'\n')
    print(json.dumps({k:v for k,v in coverage.items() if k not in ('source_report_hashes','output_hashes','accounting_missing_ids')},indent=2))


if __name__=='__main__':main()
